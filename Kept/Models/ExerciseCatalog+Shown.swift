    /// The name to show for a stored exercise name: the English one in English, otherwise the name as stored
    /// (the user's own exercises keep whatever they called them).
    static func shownName(_ stored: String) -> String {
        guard AppLanguage.current == .en, let english = shownInEnglish[stored] else { return stored }
        return english.name
    }
}

extension CatalogExercise {
    /// The exercise's name in the app's language.
    var shownName: String { ExerciseCatalog.shownName(name) }

    /// The one-line tip in the app's language.
    var shownTip: String {
        guard AppLanguage.current == .en, let english = ExerciseCatalog.shownInEnglish[name] else { return tip }
        return english.tip
    }
}

extension String {
    /// This text read as a stored exercise name, shown in the app's language.
    var exerciseShown: String { ExerciseCatalog.shownName(self) }
}
